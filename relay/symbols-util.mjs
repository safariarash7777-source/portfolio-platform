// symbols-util.mjs — C1: قاعدهٔ یگانهٔ تشخیص زیرنماد و حق‌تقدم (اخطار رسمی BrsApi)
//
// زیرنماد بلوکی/عمده: نماد ختم به رقم (لاتین، فارسی یا عربی) — مثل «فملی2»، «آوند4».
// این نمادها نباید در هیچ صف درخواستی (NAV، کندل، آرشیو کدال، چرخش دیتای جامع)
// یا خروجی اسنپ‌شات ظاهر شوند.
//
// حق تقدم: نماد ختم به «ح» — مثل «فملیح». فقط در تابلوی لحظه‌ای سهام می‌ماند؛
// وارد صف‌های تاریخی (کندل/symbol_history/آرشیو کدال) و NAV نمی‌شود.

export const SUB_TICKER_RE = /[0-9۰-۹٠-٩]$/; // رقم لاتین + فارسی + عربی در انتهای نماد

export const isSubTicker = (l18) => SUB_TICKER_RE.test((l18 || "").trim());

export const isRightsIssue = (l18) => /ح$/.test((l18 || "").trim());

/** نماد اصلی: نه زیرنماد رقم‌دار، نه حق تقدم. */
export const isMainTicker = (l18) => {
  const s = (l18 || "").trim();
  return s.length > 0 && !SUB_TICKER_RE.test(s) && !/ح$/.test(s);
};
