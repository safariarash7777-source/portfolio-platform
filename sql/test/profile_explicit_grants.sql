-- پروفایلِ امتیازِ **سخت‌گیرانه (Explicit-grant)** — فقط تست.
--
-- اینجا عمداً **هیچ** `ALTER DEFAULT PRIVILEGES`ی وجود ندارد: جدولِ تازه هیچ
-- امتیازِ خودکاری به `anon`/`authenticated` نمی‌دهد و هر دسترسی باید صریح
-- گرنت شود.
--
-- چرا این پروفایل هم لازم است: پروفایلِ Legacy تنها چیزی است که ما **دیده‌ایم**،
-- ولی تنها چیزی نیست که ممکن است **باشد**. اگر پروژه‌ای (یا نسخه‌ای از Supabase)
-- سخت‌گیرانه باشد، migration باید همچنان درست کار کند — یعنی:
--
--   • `REVOKE`ها روی چیزی که وجود ندارد نباید بشکنند (idempotent باشند)
--   • `GRANT`های صریحِ خودِ migration باید دسترسیِ لازم را بسازند، نه اینکه به
--     امتیازِ موروثی تکیه کنند
--
-- نتیجهٔ نهاییِ هر دو پروفایل باید **یکسان** باشد:
--     anon → هیچ · authenticated → SELECT, UPDATE · service_role → نوشتن
--
-- اگر روزی این دو پروفایل به نتیجهٔ متفاوت برسند، یعنی migration به یک فرضِ
-- محیطی تکیه کرده و آن فرض باید صریح شود.
-- =============================================================================

