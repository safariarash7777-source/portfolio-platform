import type { AccessInfo } from "@/lib/access";
import { formatJalali } from "@/lib/format";

/**
 * متنِ زیرِ عنوانِ پلِ حساب — فقط از قراردادِ backend، نه از حدسِ UI.
 *
 * دو تغییرِ موازی اینجا به هم رسیدند و هیچ‌کدام به‌تنهایی کافی نبود:
 *
 * ۱. `main` تفکیکِ `standing` را آورد. پیش از آن «دسترسی‌اش منقضی شده» و
 *    «هیچ‌وقت نداشته» هر دو `registered` با `via: null` بودند و یک جمله
 *    می‌گرفتند؛ کسی که اشتراکش دیروز تمام شده پیامِ خوشامدِ کاربرِ تازه می‌دید.
 * ۲. `#124` این شکاف را دید که متنِ `registered` **اصلاً نمی‌گفت دسترسی کامل
 *    فعال نیست** — فقط از نگه‌داشتنِ واچ‌لیست حرف می‌زد.
 *
 * هر دو درست‌اند و روی یک محور نیستند، پس هر دو نگه داشته شده‌اند: `standing`
 * می‌گوید **چرا** در این وضعیتیم، و `level` می‌گوید **چه چیزی فعال نیست**.
 * جملهٔ دوم از `level === "registered"` می‌آید که خودش محاسبهٔ سرور است، پس
 * حتی وقتی `standing === null` است هم ادعای نادرستی نمی‌سازد.
 *
 * `standing === null` یعنی سرور **نتوانست** بفهمد — آنجا عمداً هیچ ادعایی
 * دربارهٔ سابقهٔ کاربر نمی‌کنیم.
 */
export function accountSubtitle(access: AccessInfo): string {
  if (access.level === "full") {
    return access.expiresAt
      ? `دسترسی کامل فعال است · تا ${formatJalali(access.expiresAt, false)}`
      : "دسترسی کامل فعال است.";
  }
  if (access.level === "visitor") {
    return "واچ‌لیست، یادداشت و پیگیریِ نمادها به حسابِ شما گره می‌خورد.";
  }
  switch (access.standing) {
    case "expired":
      return access.standingSince
        ? `دورهٔ دسترسیِ کاملِ شما در ${formatJalali(access.standingSince, false)} به پایان رسیده است.`
        : "دورهٔ دسترسیِ کاملِ شما به پایان رسیده است.";
    case "revoked":
      return "دسترسیِ کاملِ شما لغو شده است. برای پیگیری با پشتیبانی تماس بگیرید.";
    case "scheduled":
      return access.standingSince
        ? `دسترسیِ کاملِ شما ثبت شده و از ${formatJalali(access.standingSince, false)} فعال می‌شود.`
        : "دسترسیِ کاملِ شما ثبت شده و هنوز شروع نشده است.";
    case "never":
      return "حساب شما فعال است و واچ‌لیست و یادداشت‌هایتان نگه داشته می‌شود. دسترسی کامل هنوز فعال نشده است.";
    default:
      // `null` — وضعیت خوانده نشد. دربارهٔ **سابقه** ساکت می‌مانیم؛ «کامل فعال
      // نیست» از `level` می‌آید نه از حدس، پس گفتنش امن است.
      return "حساب شما فعال است و واچ‌لیست و یادداشت‌هایتان نگه داشته می‌شود. دسترسی کامل فعال نیست.";
  }
}
