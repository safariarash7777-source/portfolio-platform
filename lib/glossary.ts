/** نگاشت id → term برای دسترسی سریع. */
const BY_ID = new Map(GLOSSARY.map((t) => [t.id, t]));

/** واژه با این id — نبود → null صادق (نه throw). */
export function getTerm(id: string): GlossaryTerm | null {
  return BY_ID.get(id) ?? null;
}

/** جستجوی ساده در term/short/long (بدون حساسیت به فاصلهٔ مجازی). */
export function searchGlossary(query: string): GlossaryTerm[] {
  const q = query.trim().replace(/\u200c/g, "");
  if (!q) return GLOSSARY;
  return GLOSSARY.filter((t) =>
    [t.term, t.short, t.long].some((s) => s.replace(/\u200c/g, "").includes(q))
  );
}
