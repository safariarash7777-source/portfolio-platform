// ─── نرمال‌سازی متن فارسی برای تطبیق مقاوم ───────────────────────────────────
const ZWNJ = /‌/g; // نیم‌فاصله
const WHITESPACE = /\s+/g;

/** نرمال‌سازی: حذف نیم‌فاصله و تمام فاصله‌ها + یکدست‌سازی ی/ک عربی. */
function normalize(text: string): string {
  return text
    .replace(ZWNJ, "")
    .replace(WHITESPACE, "")
    .replace(/ي/g, "ی") // ي عربی → ی فارسی
    .replace(/ك/g, "ک"); // ك عربی → ک فارسی
}

