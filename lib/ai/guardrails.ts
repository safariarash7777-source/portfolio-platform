const INJECTION_PATTERNS = RAW_INJECTION_PATTERNS.map(normalize);

/**
 * غربال ورودیِ کاربر.
 * @returns true اگر ورودی باید بلاک شود (تلاش برای دور زدن گاردریل).
 */
export function screenInput(text: string): boolean {
  if (!text) return false;
  const normalized = normalize(text.toLowerCase());
  return INJECTION_PATTERNS.some((p) => normalized.includes(p.toLowerCase()));
}

// ─── گاردِ خروجیِ استریمی (پنجرهٔ لغزان) ─────────────────────────────────────
/**
 * StreamingOutputGuard متن استریم‌شده را قطعه‌به‌قطعه می‌بلعد و:
 *  - با هر push بررسی می‌کند که آیا عبارت ممنوعی کامل شده است.
 *  - برای گرفتنِ عباراتی که روی مرز دو قطعه می‌افتند، یک «دُمِ» به‌اندازهٔ
 *    holdback نگه می‌دارد و فقط متنی را امن اعلام می‌کند که دیگر نمی‌تواند
 *    آغازِ یک عبارت ممنوع باشد.
 *
 * توجه: نرمال‌سازی فقط برای مقایسه است؛ متنِ امن خام (raw) برگردانده می‌شود.
 */
export class StreamingOutputGuard {
  private buffer = "";
  private readonly holdback: number;
  private tripped = false;

  constructor(private readonly blocked: string[] = BLOCKED_OUTPUT_PHRASES) {
    const maxLen = blocked.reduce((m, p) => Math.max(m, p.length), 0);
    // حاشیهٔ امن برای فاصله/نیم‌فاصله‌هایی که در نرمال‌سازی حذف می‌شوند.
    this.holdback = maxLen + 8;
  }

  /**
   * یک قطعهٔ جدید را اضافه و بررسی می‌کند.
   * @returns متنِ امنی که می‌توان فوراً به کلاینت فرستاد و پرچم blocked.
   */
  push(delta: string): { safe: string; blocked: boolean } {
    if (this.tripped) return { safe: "", blocked: true };
    this.buffer += delta;

    const haystack = normalize(this.buffer);
    for (const phrase of this.blocked) {
      if (phrase && haystack.includes(phrase)) {
        this.tripped = true;
        this.buffer = "";
        return { safe: "", blocked: true };
      }
    }

    // متنی که حداقل holdback کاراکتر از انتهای بافر فاصله دارد، دیگر نمی‌تواند
    // بخشی از یک عبارت ممنوعِ ناقص باشد و امن است.
    if (this.buffer.length > this.holdback) {
      const cut = this.buffer.length - this.holdback;
      const safe = this.buffer.slice(0, cut);
      this.buffer = this.buffer.slice(cut);
      return { safe, blocked: false };
    }
    return { safe: "", blocked: false };
  }

  /** در پایان جریان، باقیماندهٔ بافرِ امن را برمی‌گرداند. */
  flush(): string {
    if (this.tripped) return "";
    const out = this.buffer;
    this.buffer = "";
    return out;
  }

  get isTripped(): boolean {
    return this.tripped;
  }
}
