/**
 * آیا این قیمت می‌تواند واقعی باشد؟
 *
 * ── چرا این فایل جدا است ────────────────────────────────────────────────────
 *
 * دو سطحِ عمومی همان پاسخِ `/api/market` را رندر می‌کنند: `LiveMarket` و
 * `MarketTicker`. اولین اصلاح فقط `LiveMarket` را پوشش داد و تستِ رفتاری نشان
 * داد ردیفِ قیمتِ صفر همچنان در تیکر دیده می‌شود — یعنی گارد در یک سطح بود و
 * نشتی در سطحِ دیگر.
 *
 * دو تعریف یعنی یکی به‌روز می‌شود و دیگری نه. اینجا یک تعریف است.
 *
 * ── چرا حذفِ ردیف، نه نمایشِ صفر ────────────────────────────────────────────
 *
 * `formatToman(0)` رشتهٔ «۰ تومان» می‌سازد که از یک قیمتِ واقعی قابلِ تشخیص
 * نیست. دادهٔ نبود باید **دیده نشود**، نه اینکه به صفر تبدیل شود.
 */
export function hasRealPrice(price: number | null | undefined): boolean {
  return typeof price === "number" && Number.isFinite(price) && price > 0;
}
