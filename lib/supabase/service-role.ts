/**
 * پاسخِ یکدستِ «این قابلیت سکرتِ سرور می‌خواهد و آن سکرت نیست».
 *
 * ── چرا این فایل وجود دارد ─────────────────────────────────────────────
 * `SUPABASE_SERVICE_ROLE_KEY` روی Production ست نشده بود.
 * `createAdminClient()` پرتاب می‌کرد، هیچ مسیری آن پرتاب را نمی‌گرفت، و Next
 * آن را به **۵۰۰ با بدنهٔ خالی** تبدیل می‌کرد. از بیرون این دقیقاً شبیهِ
 * «سایت خراب است» بود؛ نه کاربر می‌فهمید چه شده، نه اپراتور می‌دانست کدام
 * متغیر غایب است. یک تنظیمِ نداشته، شبیهِ نقصِ نرم‌افزار به‌نظر می‌رسید.
 *
 * قاعدهٔ همیشگیِ این مخزن اینجا هم برقرار است: **شکست باید دیده شود و
 * نامش را بگوید.** «تنظیم نشده» و «تنظیم شده ولی خطا داد» دو تشخیصِ متفاوت‌اند
 * و دو کارِ متفاوت می‌طلبند، پس نباید یک‌شکل بیرون بیایند.
 *
 * چرا ۵۰۳ و نه ۵۰۰: سرویس **موقتاً** در دسترس نیست چون پیکربندی ناقص است، نه
 * اینکه درخواست پردازش شد و شکست. با تنظیمِ متغیر و یک redeploy برمی‌گردد.
 */

/** وضعیتِ HTTP برای «پیکربندی ناقص است»، نه «خطای پردازش». */
export const SERVICE_ROLE_GAP_STATUS = 503;

export interface ServiceRoleGap {
  /** شناسهٔ ماشین‌خوان — برای لاگ و تستِ خودکار. */
  error: "service_role_unavailable";
  /** نامِ متغیرِ غایب. مقدارش هرگز اینجا نمی‌آید، فقط نامش. */
  missingEnv: "SUPABASE_SERVICE_ROLE_KEY";
  /** پیامِ فارسیِ کاربر-رو: چه چیزی کار نمی‌کند و چه باید بشود. */
  detail: string;
}

/**
 * @param feature نامِ فارسیِ همان قابلیتی که از کار افتاده — مثلِ «پرداختِ
 *   وبینار». بدونِ آن پیام عمومی می‌شود و همان کوریِ قبلی را برمی‌گرداند.
 */
export function serviceRoleGap(feature: string): ServiceRoleGap {
  return {
    error: "service_role_unavailable",
    missingEnv: "SUPABASE_SERVICE_ROLE_KEY",
    detail: `${feature} در دسترس نیست: متغیرِ سرورِ «SUPABASE_SERVICE_ROLE_KEY» تنظیم نشده. این یک نقصِ پیکربندی است، نه خطای شما — پس از تنظیمِ متغیر و انتشارِ دوباره برمی‌گردد.`,
  };
}
